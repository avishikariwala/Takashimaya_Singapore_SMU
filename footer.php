    // Mobile navigation toggle
    const menuButton = document.querySelector('.menu-toggle');
    const nav = document.querySelector('#mainNav');
    if (menuButton && nav) {
      menuButton.addEventListener('click', () => {
        const isOpen = nav.classList.toggle('open');
        menuButton.setAttribute('aria-expanded', String(isOpen));
        menuButton.setAttribute('aria-label', isOpen ? 'Close navigation' : 'Open navigation');
        menuButton.textContent = isOpen ? '×' : '☰';
      });
      nav.querySelectorAll('a').forEach(link => link.addEventListener('click', () => {
        nav.classList.remove('open');
        menuButton.setAttribute('aria-expanded', 'false');
        menuButton.setAttribute('aria-label', 'Open navigation');
        menuButton.textContent = '☰';
      }));
    }

    // Dynamic year fallback
    const yearSpan = document.querySelector('#year');
    if (yearSpan) {
      yearSpan.textContent = new Date().getFullYear();
    }

    // Hero pause button handler (homepage)
    const pauseHeroBtn = document.querySelector('#pauseHero');
    if (pauseHeroBtn) {
      pauseHeroBtn.addEventListener('click', function () {
        const paused = this.textContent.trim() === 'Ⅱ';
        this.textContent = paused ? '▶' : 'Ⅱ';
        this.setAttribute('aria-label', paused ? 'Resume slideshow' : 'Pause slideshow');
      });
    }

    // Subtle entrance effect for elements
    if ('IntersectionObserver' in window && !window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
      const revealTargets = document.querySelectorAll('.quick-card, .story-card, .promo-card, .about-copy, .info-card');
      const observer = new IntersectionObserver((entries, obs) => {
        entries.forEach(entry => {
          if (entry.isIntersecting) {
            entry.target.classList.add('reveal');
            obs.unobserve(entry.target);
          }
        });
      }, { threshold: 0.12 });
      revealTargets.forEach(target => observer.observe(target));
    }

    // Global Search Toggle handler
    const searchToggleBtn = document.querySelector('#searchToggle');
    const searchPanelEl = document.querySelector('#searchPanel');
    const siteSearchInput = document.querySelector('#siteSearch');
    if (searchToggleBtn && searchPanelEl) {
      searchToggleBtn.addEventListener('click', (e) => {
        e.preventDefault();
        const isOpen = searchPanelEl.classList.toggle('open');
        if (isOpen && siteSearchInput) {
          siteSearchInput.focus();
        }
      });
    }

    // Global Toast Helper
    function showSiteToast(msg) {
      const t = document.querySelector('#toast');
      if (!t) return;
      t.textContent = msg;
      t.classList.add('show');
      clearTimeout(window.__toastTimer);
      window.__toastTimer = setTimeout(() => t.classList.remove('show'), 2600);
    }

    // Global Favourite button toggle
    const favBtn = document.querySelector('#favoriteBtn');
    const heartIcon = document.querySelector('#heartSvg');
    if (favBtn && heartIcon && !favBtn.dataset.bound) {
      favBtn.dataset.bound = 'true';
      let isSaved = false;
      favBtn.addEventListener('click', (e) => {
        e.preventDefault();
        isSaved = !isSaved;
        heartIcon.innerHTML = isSaved
          ? '<path d="M20.8 8.8c0 5.1-8.8 10.2-8.8 10.2S3.2 13.9 3.2 8.8A4.5 4.5 0 0 1 12 6.7a4.5 4.5 0 0 1 8.8 2.1Z" fill="#c8102e"/>'
          : '<path d="M20.8 8.8c0 5.1-8.8 10.2-8.8 10.2S3.2 13.9 3.2 8.8A4.5 4.5 0 0 1 12 6.7a4.5 4.5 0 0 1 8.8 2.1Z"/>';
        showSiteToast(isSaved ? 'Added to your favourites' : 'Removed from your favourites');
      });
    }
